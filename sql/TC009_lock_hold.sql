-- DB 更新失敗の再現: batch 実行中だけ対象テーブルをロックする
--   setup.db_lock に指定すると、別接続でこの SQL を実行したまま batch を起動し、
--   batch 終了後にロールバックする（保持したままにはならない）。
--
--   batch 側は更新でロック待ちになり、lock_timeout を超えるとエラーになる。
--   これで「DB 更新に失敗したとき、ファイルをエラーへ退避するか」
--   「DB がロールバックされるか」を毎回同じ手順で検証できる。
-- =============================================================================
BEGIN TRAN;
UPDATE T_ORDER WITH (TABLOCKX) SET STATUS = STATUS WHERE ORDER_ID = 1;
-- COMMIT しない。ツールが batch 終了後に ROLLBACK する
