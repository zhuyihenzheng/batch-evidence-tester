-- =============================================================================
-- 【方式 A】列単位の権限剥奪 — 最終 UPDATE だけを失敗させる（最も侵襲が小さい）
--
--   想定する batch の流れ:
--     1. INSERT して COMMIT   … 成功させたい
--     2. ファイル移動          … 成功させたい
--     3. UPLOAD_TIME を UPDATE … ここだけ失敗させたい
--
--   列単位で DENY できるので、INSERT には影響せず 3 だけが失敗する。
--   スキーマを変更しないため、戻し忘れても影響は権限だけに閉じる。
--   ※ 権限変更の権限が必要。無い環境では方式 B（CHECK 制約）を使う。
-- =============================================================================
DENY UPDATE ON dbo.T_ORDER(UPLOAD_TIME) TO [batch_test_user];
GO
