-- =============================================================================
-- TC007 異常系: DB 更新失敗の注入（一意制約違反）
--   batch が INSERT する予定のキーを先に埋めておき、実行時に PK 違反を起こさせる。
--   DB 側の制約を一時的に外すのではなく「衝突するデータを置く」方式にしているのは、
--   スキーマを変更しないためテスト後に環境が壊れないから。
-- =============================================================================
DELETE FROM T_ORDER WHERE ORDER_ID IN (1, 2);
GO

-- batch は ORDER_ID=1 を INSERT しようとするが、先に別内容で埋めておく
INSERT INTO T_ORDER (ORDER_ID, ORDER_NO, CUSTOMER_NM, AMOUNT, STATUS, UPDATED_AT)
VALUES (1, 'DUMMY', N'衝突用ダミー', 0, N'既存', '2026-08-03 08:00:00');
GO
